function renderInDepth(topic, category, rng) {
  const pool = IN_DEPTH_BANK[category];
  if (!pool || !pool.length) return '';
  // 모든 단락 사용 (7개)
  const items = shuffle(rng, pool);
  let out = `## 한 걸음 더 들어가 보기\n\n`;
  for (const it of items) out += `${replaceTopic(it, topic)}\n\n`;
  return out;
}

