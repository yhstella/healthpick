function renderTips(topic, category, rng) {
  const bank = TIPS_BANK[category];
  if (!bank) return '';
  const intro = replaceTopic(bank.intro, topic);
  // 팁은 풀의 모든 항목을 사용
  const items = shuffle(rng, bank.items);
  let out = `## 실생활 적용 팁\n\n${intro}\n\n`;
  for (const it of items) out += `- ${replaceTopic(it, topic)}\n`;
  out += `\n`;
  return out;
}

