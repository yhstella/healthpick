function renderContext(topic, category, rng) {
  const pool = CONTEXT_BANK[category];
  if (!pool || !pool.length) return '';
  const items = shuffle(rng, pool);
  let out = `## 알아두면 좋은 배경 정보\n\n`;
  for (const it of items) out += `${replaceTopic(it, topic)}\n\n`;
  return out;
}

function renderBonus(topic, category, rng) {
  const bank = BONUS_BANK[category];
  if (!bank) return '';
  // 모든 항목 사용
  const items = shuffle(rng, bank.items);
  let out = `## ${bank.title}\n\n`;
  for (const it of items) out += `${replaceTopic(it, topic)}\n\n`;
  return out;
}

export function renderBody({ topic, category, sectionKey, rng }) {
  const sections = TEMPLATES[category][sectionKey] || [];
  const intro = replaceTopic(pick(rng, INTRO[category]), topic);
  const outro = replaceTopic(pick(rng, OUTRO[category]), topic);

  let body = `${intro}\n\n`;

  // 메인 섹션: 가능하면 모든 섹션 사용 (4~5천자 목표)
  // 섹션 순서는 자연스러움을 위해 원래 순서 유지 (셔플 하지 않음)
  for (const sec of sections) {
    body += `## ${sec.h}\n\n`;
    const paras = sec.p || [];
    // 단락은 가능한 모두 사용 (4~5천자 본문 목표)
    const orderedParas = shuffle(rng, paras);
    for (const p of orderedParas) {
      body += `${replaceTopic(p, topic)}\n\n`;
    }
    // 불릿 리스트: 가능한 모두 사용
    if (sec.b && sec.b.length) {
      const picked = shuffle(rng, sec.b);
      for (const [lead, items] of picked) {
        body += `${replaceTopic(lead, topic)}\n\n`;
        for (const item of items) {
          body += `- ${replaceTopic(item, topic)}\n`;
        }
        body += `\n`;
      }
    }
  }

  // 전환 문장
  const transitions = TRANSITIONS[category];
  if (transitions && transitions.length) {
    body += `${replaceTopic(pick(rng, transitions), topic)}\n\n`;
  }

  // 보조 섹션 1: 한 걸음 더 들어가 보기 (심층 단락)
  body += renderInDepth(topic, category, rng);

  // 보조 섹션 2: 알아두면 좋은 배경 정보
  body += renderContext(topic, category, rng);

  // 보조 섹션 3: 실생활 적용 팁
  body += renderTips(topic, category, rng);

  // 보조 섹션 4: FAQ
  body += renderFAQ(topic, category, rng);

  // 보조 섹션 5: 추가로 알아두면 좋은 점
  body += renderBonus(topic, category, rng);

  // 보조 섹션 6: 체크리스트
  body += renderChecklist(topic, category, rng);

  // 보조 섹션 7: 주의사항·면책
  body += renderCautions(topic, category);

  // 마무리
  body += `## 마무리\n\n${outro}\n`;
  return body;
}
