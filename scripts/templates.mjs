function renderFAQ(topic, category, rng) {
  const pool = FAQ_BANK[category];
  if (!pool || !pool.length) return '';
  // FAQ는 풀에 있는 모든 질문을 사용 (보통 7~8개)
  const chosen = shuffle(rng, pool);
  let out = `## 자주 묻는 질문\n\n`;
  out += `${topic}에 대해 자주 받는 질문들을 정리했습니다. 본인의 상황과 비교해 보시면 도움이 됩니다.\n\n`;
  for (const f of chosen) {
    const q = replaceTopic(f.q, topic);
    const a = replaceTopic(f.a, topic);
    out += `**Q. ${q}**\n\n${a}\n\n`;
  }
  return out;
}

function renderChecklist(topic, category, rng) {
  const bank = CHECKLIST_BANK[category];
  if (!bank) return '';
  const intro = replaceTopic(bank.intro, topic);
  const title = replaceTopic(bank.title, topic);
  // 모든 항목 사용
  const items = shuffle(rng, bank.items);
  let out = `## ${title}\n\n${intro}\n\n`;
  for (const it of items) {
    out += `- ${replaceTopic(it, topic)}\n`;
  }
  out += `\n`;
  return out;
}

